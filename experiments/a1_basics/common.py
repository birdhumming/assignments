"""Shared helpers for the a1_basics experiment files.

Every run is tagged with "a1" plus a problem tag (e.g. "a1-p1a-lr") so the
W&B project can be sliced per sub-question. Run names are generated by
train.training_run_name from the config diff, so identical configs used by
several problems collapse to a single training run (see launch_all.py).
"""

from dataclasses import replace

from train import TrainConfig, training_run_name


def tagged(config: TrainConfig, *tags: str) -> TrainConfig:
    return replace(config, wandb_tags=tuple(dict.fromkeys(("a1", *tags))))


def run(*tags: str, **changes) -> TrainConfig:
    return tagged(TrainConfig(**changes), *tags)


def dedupe(configs):
    """Drop configs whose generated run name was already seen (first wins)."""
    seen = set()
    unique = []
    for config in configs:
        name = training_run_name(config)
        if name in seen:
            continue
        seen.add(name)
        unique.append(config)
    return unique
